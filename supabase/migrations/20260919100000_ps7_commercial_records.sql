-- =====================================================================
-- 8. Atomic save: header + lines (+ explicit document links) in ONE
--    transaction. SECURITY INVOKER: every RLS rule and trigger applies.
-- =====================================================================
-- p_contract: header fields (id for update). p_items: full line set; lines
-- with an id are updated, without id inserted, missing ids deleted.
-- p_doc_ids: existing documents to link to this contract (document-first
-- flow). No binary is copied; only a link row is added.
create or replace function public.contract_save(p_contract jsonb, p_items jsonb, p_doc_ids bigint[])
returns bigint language plpgsql security invoker
set search_path = public, pg_temp as $$
declare
  cid bigint := nullif(p_contract->>'id', '')::bigint;
  it jsonb; keep bigint[] := '{}'; iid bigint; n int := 0;
begin
  if cid is null then
    insert into public.contracts (customer_id, job_id, quote_id, title, reference_no, status,
      signed_at, currency, vat_mode, vat_rate, payment_terms, note)
    values ((p_contract->>'customer_id')::bigint, nullif(p_contract->>'job_id','')::bigint,
      nullif(p_contract->>'quote_id','')::bigint, p_contract->>'title',
      nullif(trim(p_contract->>'reference_no'),''), coalesce(p_contract->>'status','taslak'),
      nullif(p_contract->>'signed_at','')::date, coalesce(nullif(p_contract->>'currency',''),'TRY'),
      coalesce(nullif(p_contract->>'vat_mode',''),'haric'), nullif(p_contract->>'vat_rate','')::numeric,
      nullif(trim(p_contract->>'payment_terms'),''), nullif(trim(p_contract->>'note'),''))
    returning id into cid;
  else
    update public.contracts set
      customer_id   = (p_contract->>'customer_id')::bigint,
      job_id        = nullif(p_contract->>'job_id','')::bigint,
      quote_id      = nullif(p_contract->>'quote_id','')::bigint,
      title         = p_contract->>'title',
      reference_no  = nullif(trim(p_contract->>'reference_no'),''),
      status        = coalesce(p_contract->>'status','taslak'),
      signed_at     = nullif(p_contract->>'signed_at','')::date,
      currency      = coalesce(nullif(p_contract->>'currency',''),'TRY'),
      vat_mode      = coalesce(nullif(p_contract->>'vat_mode',''),'haric'),
      vat_rate      = nullif(p_contract->>'vat_rate','')::numeric,
      payment_terms = nullif(trim(p_contract->>'payment_terms'),''),
      note          = nullif(trim(p_contract->>'note'),'')
    where id = cid;
    get diagnostics n = row_count;
    if n = 0 then raise exception 'Bu sözleşmeyi değiştirme yetkiniz yok.' using errcode = '42501'; end if;
  end if;

  if p_items is not null and jsonb_typeof(p_items) = 'array' then
    for it in select * from jsonb_array_elements(p_items) loop
      iid := nullif(it->>'id','')::bigint;
      if iid is not null then
        update public.contract_items set
          item_type = coalesce(nullif(it->>'item_type',''),'mecra'),
          description = nullif(trim(it->>'description'),''),
          mecra_id = nullif(it->>'mecra_id','')::bigint, unit_id = nullif(it->>'unit_id','')::bigint,
          quantity = coalesce(nullif(it->>'quantity','')::numeric, 1),
          start_date = nullif(it->>'start_date','')::date, end_date = nullif(it->>'end_date','')::date,
          duration_note = nullif(trim(it->>'duration_note'),''),
          unit_price = nullif(it->>'unit_price','')::numeric, line_total = nullif(it->>'line_total','')::numeric,
          note = nullif(trim(it->>'note'),''), sort = coalesce(nullif(it->>'sort','')::int, 0)
        where id = iid and contract_id = cid;
        get diagnostics n = row_count;
        if n = 0 then raise exception 'Kalem bu sözleşmeye ait değil.' using errcode = '42501'; end if;
      else
        insert into public.contract_items (contract_id, item_type, description, mecra_id, unit_id,
          quantity, start_date, end_date, duration_note, unit_price, line_total, note, sort)
        values (cid, coalesce(nullif(it->>'item_type',''),'mecra'), nullif(trim(it->>'description'),''),
          nullif(it->>'mecra_id','')::bigint, nullif(it->>'unit_id','')::bigint,
          coalesce(nullif(it->>'quantity','')::numeric, 1),
          nullif(it->>'start_date','')::date, nullif(it->>'end_date','')::date,
          nullif(trim(it->>'duration_note'),''), nullif(it->>'unit_price','')::numeric,
          nullif(it->>'line_total','')::numeric, nullif(trim(it->>'note'),''),
          coalesce(nullif(it->>'sort','')::int, 0))
        returning id into iid;
      end if;
      keep := keep || iid;
    end loop;
    delete from public.contract_items where contract_id = cid and not (id = any(keep));
  end if;

  if p_doc_ids is not null and array_length(p_doc_ids, 1) > 0 then
    insert into public.document_links (document_id, contract_id)
    select d, cid from unnest(p_doc_ids) d
    on conflict do nothing;
  end if;
  return cid;
end;
