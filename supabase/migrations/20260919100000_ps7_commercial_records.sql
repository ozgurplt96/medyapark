-- =====================================================================
-- 5. contracts triggers
-- =====================================================================
-- Identity + lifecycle guard. A policy cannot compare OLD/NEW, so the rules
-- live here:
--   * creator comes from the JWT (admin may keep a supplied value: restore)
--   * created_by / created_at immutable
--   * cancelled is terminal for non-admins
--   * a signed contract cannot silently go back to draft (that would re-open
--     hard delete of commercial truth) except by an admin
--   * cancelled_at is system-stamped
create or replace function public._trg_contracts_kimlik() returns trigger
language plpgsql security definer
set search_path = public, auth, pg_temp as $$
begin
  if tg_op = 'INSERT' then
    if not public.is_admin() or new.created_by_team_id is null then
      new.created_by_team_id := public.current_team_id();
    end if;
    new.created_at := now();
    new.updated_at := null;
    new.cancelled_at := case when new.status = 'iptal' then now() end;
    return new;
  end if;

  if new.created_by_team_id is distinct from old.created_by_team_id
     or new.created_at is distinct from old.created_at then
    raise exception 'Sözleşmenin oluşturan bilgisi değiştirilemez.' using errcode = '42501';
  end if;
  if not public.is_admin() then
    if old.status = 'iptal' and new.status <> 'iptal' then
      raise exception 'İptal edilmiş sözleşme yeniden açılamaz.' using errcode = '42501';
    end if;
    if old.status = 'imzali' and new.status = 'taslak' then
      raise exception 'İmzalı sözleşme taslağa döndürülemez; gerekiyorsa iptal edin.' using errcode = '42501';
    end if;
  end if;
  if new.status = 'iptal' and old.status <> 'iptal' then new.cancelled_at := now();
  elsif new.status <> 'iptal' then new.cancelled_at := null;
  else new.cancelled_at := old.cancelled_at;
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists trg_contracts_kimlik on public.contracts;
create trigger trg_contracts_kimlik before insert or update on public.contracts
  for each row execute function public._trg_contracts_kimlik();

-- A SIGNED contract must carry at least one commercial line. Checked at
-- COMMIT so header + items are saved in one transaction (`contract_save`).
-- A draft may be empty while it is being prepared.
create or replace function public._sozlesme_kalem_kontrol(p_id bigint) returns void
language plpgsql security definer
set search_path = public, pg_temp as $$
begin
  if exists (select 1 from public.contracts c where c.id = p_id and c.status = 'imzali')
     and not exists (select 1 from public.contract_items i where i.contract_id = p_id) then
    raise exception 'İmzalı bir sözleşmenin en az bir kalemi olmalı.' using errcode = '23514';
  end if;
end;
$$;
revoke all on function public._sozlesme_kalem_kontrol(bigint) from public, anon, authenticated;

create or replace function public._trg_contracts_kalem() returns trigger
language plpgsql security definer
set search_path = public, pg_temp as $$
begin
  perform public._sozlesme_kalem_kontrol(new.id);
  return null;
end;
$$;
drop trigger if exists trg_contracts_kalem on public.contracts;
create constraint trigger trg_contracts_kalem
  after insert or update of status on public.contracts
  deferrable initially deferred
  for each row execute function public._trg_contracts_kalem();

create or replace function public._trg_contract_items_kalem() returns trigger
language plpgsql security definer
set search_path = public, pg_temp as $$
begin
  perform public._sozlesme_kalem_kontrol(old.contract_id);
  return null;
end;
$$;
drop trigger if exists trg_contract_items_kalem on public.contract_items;
create constraint trigger trg_contract_items_kalem
  after delete on public.contract_items
  deferrable initially deferred
  for each row execute function public._trg_contract_items_kalem();

-- Lines of a cancelled contract are frozen for non-admins (history).
create or replace function public._trg_contract_items_koru() returns trigger
language plpgsql security definer
set search_path = public, auth, pg_temp as $$
declare st text; cid bigint;
begin
  cid := coalesce(new.contract_id, old.contract_id);
  select status into st from public.contracts where id = cid;
  if st = 'iptal' and not public.is_admin() then
    raise exception 'İptal edilmiş sözleşmenin kalemleri değiştirilemez.' using errcode = '42501';
  end if;
  if tg_op = 'UPDATE' then
    if new.contract_id is distinct from old.contract_id then
      raise exception 'Kalem başka sözleşmeye taşınamaz.' using errcode = '42501';
    end if;
    new.updated_at := now();
    new.created_at := old.created_at;
  end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;
drop trigger if exists trg_contract_items_koru on public.contract_items;
create trigger trg_contract_items_koru before insert or update or delete on public.contract_items
  for each row execute function public._trg_contract_items_koru();

-- =====================================================================
-- 6. Compatibility: jobs.contract_status derived from structured contracts
-- =====================================================================
-- Deterministic rule for a Work that has ANY structured contract:
--   any signed -> 'signed', else any draft -> 'pending', else (all cancelled)
--   -> 'missing'. A Work whose last contract was deleted -> 'missing'.
-- A Work with no structured contracts at all keeps its legacy value.
-- The sync must not emit the S4.4 `work_contract` movement: the contract
-- trigger already emits the ONE meaningful business event.
create or replace function public._is_sozlesme_senk(p_job bigint) returns void
language plpgsql security definer
set search_path = public, pg_temp as $$
declare yeni text;
begin
  if p_job is null then return; end if;
  select case when bool_or(status = 'imzali') then 'signed'
              when bool_or(status = 'taslak') then 'pending'
              else 'missing' end
    into yeni from public.contracts where job_id = p_job;
  yeni := coalesce(yeni, 'missing');
  perform set_config('medyapark.sozlesme_senk', '1', true);
  update public.jobs set contract_status = yeni
   where id = p_job and contract_status is distinct from yeni;
  perform set_config('medyapark.sozlesme_senk', '', true);
end;
$$;
revoke all on function public._is_sozlesme_senk(bigint) from public, anon, authenticated;

-- Trusted movements for the three meaningful contract actions only.
-- Title/note/payment edits and line edits emit nothing (no noise).
-- Movements live on the Work timeline, so a Work-less (company-level)
-- contract produces none (entries history is Work-scoped, S4.4).
create or replace function public._trg_contracts_hareket() returns trigger
language plpgsql security definer
set search_path = public, auth, pg_temp as $$
begin
  if tg_op = 'INSERT' then
    perform public._sistem_hareketi(new.job_id, 'contract_created',
      'Sözleşme kaydı oluşturuldu: ' || new.title
      || case when new.status = 'imzali' then ' (imzalı)' else '' end);
    perform public._is_sozlesme_senk(new.job_id);
    return new;
  end if;
  if tg_op = 'DELETE' then
    perform public._is_sozlesme_senk(old.job_id);
    return old;
  end if;
  if new.status is distinct from old.status then
    if new.status = 'imzali' then
      perform public._sistem_hareketi(new.job_id, 'contract_signed',
        'Sözleşme imzalı olarak işaretlendi: ' || new.title);
    elsif new.status = 'iptal' then
      perform public._sistem_hareketi(new.job_id, 'contract_cancelled',
        'Sözleşme iptal edildi: ' || new.title);
    end if;
  end if;
  if new.job_id is distinct from old.job_id then
    perform public._is_sozlesme_senk(old.job_id);
  end if;
  if new.status is distinct from old.status or new.job_id is distinct from old.job_id then
    perform public._is_sozlesme_senk(new.job_id);
  end if;
  return new;
end;
$$;
drop trigger if exists trg_contracts_hareket on public.contracts;
create trigger trg_contracts_hareket after insert or update or delete on public.contracts
  for each row execute function public._trg_contracts_hareket();

-- S4.4 jobs trigger, unchanged except: a contract_status change caused by
-- the structured-contract sync emits no second movement.
create or replace function public._trg_jobs_hareket() returns trigger
language plpgsql security definer
set search_path = public, auth, pg_temp as $$
begin
  if tg_op = 'INSERT' then
    perform public._sistem_hareketi(new.id, 'work_created', 'İş oluşturuldu.');
    return new;
  end if;

  if new.status is distinct from old.status then
    perform public._sistem_hareketi(new.id, 'work_phase',
      'Aşama değişti: ' || public._lbl('faz', old.status) || ' → ' || public._lbl('faz', new.status));
  end if;

  if new.lifecycle_status is distinct from old.lifecycle_status then
    perform public._sistem_hareketi(new.id, 'work_lifecycle',
      'Durum değişti: ' || public._lbl('yasam', old.lifecycle_status) || ' → '
      || public._lbl('yasam', new.lifecycle_status)
      || case when new.lifecycle_status = 'kapandi' and new.closed_reason is not null
              then ' (' || public._lbl('kapanis', new.closed_reason) || ')' else '' end);
  end if;

  if new.contract_status is distinct from old.contract_status
     and coalesce(current_setting('medyapark.sozlesme_senk', true), '') <> '1' then
    perform public._sistem_hareketi(new.id, 'work_contract',
      'Sözleşme durumu: ' || public._lbl('sozlesme', old.contract_status) || ' → '
      || public._lbl('sozlesme', new.contract_status));
  end if;

  if new.accounting_status is distinct from old.accounting_status then
    perform public._sistem_hareketi(new.id, 'work_accounting',
      'Muhasebe durumu: ' || public._lbl('muhasebe', old.accounting_status) || ' → '
      || public._lbl('muhasebe', new.accounting_status));
  end if;

  return new;
end;
$$;

