-- Product Simplification Sprint 7 — Commercial Records foundation
--
-- CANONICAL NOTE: 06 §14 / D-229 embed a single primary Contract on `jobs`
-- (`contract_*`) and allow a separate `contracts` table "only when a real
-- multi-contract / amendment need exists". The reviewed Medyapark contracts
-- prove that need: one agreement carries several surfaces, media types,
-- periods and prices (MIÇI M1: two Megalight faces on one line; Onatça: two
-- wall locations with different prices; Eral: rent line + separate montaj
-- line), and company-level agreements exist outside a single Work. The
-- embedded fields cannot hold that without flattening. This migration opens
-- exactly the conditional table 06 §14 foresaw — nothing more.
--
-- MODEL
--   contracts        commercial agreement header (NOT the PDF binary)
--   contract_items   1..N commercial lines (surface/group, qty, period, amount)
--   document_links   gains `contract_id` (still exactly one target per row)
--
-- NOT HERE (explicit non-goals): no booking/occupancy/LED placement is created
-- from a contract item (Sprint 8); no invoice/payment engine; no quote
-- redesign — `quotes` stays the one structured Offer object.
--
-- `jobs.contract_*` becomes COMPATIBILITY-ONLY: `contract_status` is derived
-- from structured contracts by trigger whenever the Work has any; the UI no
-- longer edits these columns. Existing columns are not dropped.

-- =====================================================================
-- 1. contracts
-- =====================================================================
create table if not exists public.contracts (
  id                  bigint generated by default as identity primary key,
  customer_id         bigint not null references public.customers(id) on delete restrict,
  job_id              bigint null     references public.jobs(id)      on delete set null,
  quote_id            bigint null     references public.quotes(id)    on delete set null,
  title               text   not null,
  reference_no        text   null,
  status              text   not null default 'taslak',
  signed_at           date   null,
  currency            text   not null default 'TRY',
  vat_mode            text   not null default 'haric',
  vat_rate            numeric(5,2) null default 20,
  payment_terms       text   null,
  note                text   null,
  cancelled_at        timestamptz null,
  created_by_team_id  bigint null references public.team(id) on delete set null,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz null,
  constraint contracts_title_len    check (length(trim(title)) between 1 and 200),
  constraint contracts_status_check check (status in ('taslak','imzali','iptal')),
  constraint contracts_currency_chk check (currency ~ '^[A-Z]{3}$'),
  -- +KDV (haric) / KDV dahil (dahil) / not stated (belirtilmemis). No tax engine.
  constraint contracts_vat_mode_chk check (vat_mode in ('haric','dahil','belirtilmemis')),
  constraint contracts_vat_rate_chk check (vat_rate is null or (vat_rate >= 0 and vat_rate <= 100))
);

create index if not exists contracts_customer_idx on public.contracts (customer_id, created_at desc);
create index if not exists contracts_job_idx      on public.contracts (job_id) where job_id is not null;
create index if not exists contracts_quote_idx    on public.contracts (quote_id) where quote_id is not null;
create index if not exists contracts_status_idx   on public.contracts (status);

-- =====================================================================
-- 2. contract_items
-- =====================================================================
-- Line amount is the contractual truth. `unit_price` is optional: the real
-- contracts state a LINE total (e.g. 2 faces -> 110.000 TL). The UI may
-- default line_total = quantity x unit_price, but never overwrites an
-- explicitly entered line_total.
create table if not exists public.contract_items (
  id             bigint generated by default as identity primary key,
  contract_id    bigint not null references public.contracts(id) on delete cascade,
  item_type      text   not null default 'mecra',
  description    text   null,
  -- Optional, non-blocking media references. A reference never mutates
  -- Media and never creates a booking.
  mecra_id       bigint null references public.mecralar(id) on delete set null,
  unit_id        bigint null references public.units(id)    on delete set null,
  quantity       numeric(10,2) not null default 1,
  start_date     date null,
  end_date       date null,
  duration_note  text null,        -- "12 Ay", "3 ay", "15 sn"
  unit_price     numeric(14,2) null,
  line_total     numeric(14,2) null,
  note           text null,
  sort           integer not null default 0,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz null,
  constraint contract_items_type_chk  check (item_type in ('mecra','baski','montaj','produksiyon','hizmet','diger')),
  constraint contract_items_qty_chk   check (quantity > 0),
  constraint contract_items_dates_chk check (end_date is null or start_date is null or end_date >= start_date),
  constraint contract_items_money_chk check ((unit_price is null or unit_price >= 0)
                                         and (line_total is null or line_total >= 0)),
  -- A line must say WHAT it is: a description or a media reference.
  constraint contract_items_meaning_chk check (
    nullif(trim(coalesce(description, '')), '') is not null or unit_id is not null or mecra_id is not null)
);

create index if not exists contract_items_contract_idx on public.contract_items (contract_id, sort, id);
create index if not exists contract_items_unit_idx     on public.contract_items (unit_id) where unit_id is not null;
create index if not exists contract_items_dates_idx    on public.contract_items (start_date, end_date);

