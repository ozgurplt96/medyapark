CREATE OR REPLACE FUNCTION "public"."approve_quote"("p_quote_id" bigint) RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SET "search_path" TO 'public', 'pg_temp'
    AS $$
declare
  q record; it record; ex record;
  cust_id bigint; reserved int := 0; conflicts text[] := '{}'; m_id bigint; job_title text;
begin
  select * into q from quotes where id = p_quote_id;
  if not found then return jsonb_build_object('done', false); end if;

  -- Müşteri bul/oluştur
  if coalesce(q.eposta,'') <> '' then
    select id into cust_id from customers where eposta = q.eposta limit 1;
  end if;
  if cust_id is null and coalesce(q.firma,'') <> '' then
    select id into cust_id from customers where firma = q.firma limit 1;
  end if;
  if cust_id is null then
    insert into customers (firma, ilgili_kisi, telefon, eposta)
    values (coalesce(nullif(q.firma,''), nullif(q.customer_name,''), 'Müşteri'), q.customer_name, q.telefon, q.eposta)
    returning id into cust_id;
  end if;

  -- Ayları rezerve et, çakışmaları topla
  for it in select * from quote_items
            where quote_id = p_quote_id and unit_id is not null and ym is not null loop
    select status, customer_id into ex from bookings where unit_id = it.unit_id and ym = it.ym;
    if found and ex.status = 'dolu' and coalesce(ex.customer_id, -1) <> cust_id then
      conflicts := array_append(conflicts, coalesce(it.unit_name,'?') || ' · ' || it.ym);
      continue;
    end if;
    insert into bookings (unit_id, ym, status, customer_id)
    values (it.unit_id, it.ym, 'dolu', cust_id)
    on conflict (unit_id, ym) do update set status='dolu', customer_id=excluded.customer_id;
    reserved := reserved + 1;
    if m_id is null then select mecra_id into m_id from units where id = it.unit_id; end if;
  end loop;

  -- İş kartı (aynı teklif için tekrar açma)
  job_title := coalesce(nullif(q.firma,''), nullif(q.customer_name,''), 'Müşteri') || ' — Teklif #' || p_quote_id;
  if not exists (select 1 from jobs where title = job_title) then
    insert into jobs (title, customer_id, mecra_id, status, note)
    values (job_title, cust_id, m_id, 'tasarim', 'Onaylanan tekliften otomatik oluşturuldu.');
  end if;

  update quotes set status = 'onaylandi' where id = p_quote_id;
  return jsonb_build_object('reserved', reserved, 'conflicts', to_jsonb(conflicts), 'customer_id', cust_id);
end $$;


