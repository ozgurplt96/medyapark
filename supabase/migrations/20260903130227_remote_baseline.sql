CREATE OR REPLACE FUNCTION "public"."suppliers_sync_legacy"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    AS $$
begin
  new.firma := coalesce(new.firma, new.name);
  new.name  := coalesce(new.name,  new.firma);
  new.kategori := coalesce(new.kategori, new.type);
  new.type     := coalesce(new.type,     new.kategori);
  return new;
end $$;


