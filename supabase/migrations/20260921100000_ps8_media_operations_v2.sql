-- A legacy monthly write can no longer create a second truth next to an
-- effective placement on the same face (the admin legacy import path).
create or replace function public._trg_bookings_eski_koru() returns trigger
language plpgsql security definer
set search_path = public, pg_temp as $$
declare v_bas date; v_mode text;
begin
  if new.superseded_by_placement_id is not null then return new; end if;
  select coalesce(a.occupancy_mode, 'exclusive') into v_mode
    from public.units u left join public.alt_mecralar a on a.id = u.alt_mecra_id where u.id = new.unit_id;
  if v_mode = 'concurrent' then return new; end if;
  v_bas := to_date(new.ym || '-01', 'YYYY-MM-DD');
  if exists (select 1 from public.media_placements p
              where p.unit_id = new.unit_id and p.commitment <> 'cancelled'
                and daterange(p.start_date, p.end_date, '[]')
                    && daterange(v_bas, (v_bas + interval '1 month - 1 day')::date, '[]')) then
    raise exception '% · %: bu ay için güncel bir yerleşim kaydı var; eski aylık kayıt yazılamaz.',
      public._medya_hedef_adi(new.unit_id, null), new.ym using errcode = '23P01';
  end if;
  return new;
end;
$$;
drop trigger if exists trg_bookings_eski_koru on public.bookings;
create trigger trg_bookings_eski_koru before insert or update of unit_id, ym, status, superseded_by_placement_id
  on public.bookings for each row execute function public._trg_bookings_eski_koru();

