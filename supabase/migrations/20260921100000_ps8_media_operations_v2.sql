create or replace function public._ps8_eski_kesin_birlestir()
returns int language plpgsql security definer
set search_path = public, pg_temp as $$
declare g record; v_id bigint; n int := 0;
begin
  perform set_config('medyapark.eski_devral', '1', true);
  perform set_config('medyapark.medya_sessiz', '1', true);   -- a migration is not a business event
  for g in
    select b.unit_id, b.customer_id, b.period_start as ps, b.period_end as pe, b.status,
           array_agg(b.id order by b.ym) as ids, array_agg(b.ym::text order by b.ym) as yms,
           count(distinct b.work_id) as is_say, max(b.work_id) as work_id,
           max(b.source_quote_id) as quote_id
      from public.bookings b
      join public.units u on u.id = b.unit_id
      left join public.alt_mecralar a on a.id = u.alt_mecra_id
     where b.period_start is not null and b.period_end is not null
       and b.customer_id is not null and b.superseded_by_placement_id is null
       and u.active and coalesce(a.occupancy_mode, 'exclusive') = 'exclusive'
     group by b.unit_id, b.customer_id, b.period_start, b.period_end, b.status
  loop
    -- deterministic only: the rows cover EXACTLY the months the one real
    -- period spans, and at most one Work is involved.
    if g.yms is distinct from (select array_agg(to_char(m, 'YYYY-MM') order by m)
                                 from generate_series(date_trunc('month', g.ps::timestamp),
                                                      date_trunc('month', g.pe::timestamp),
                                                      interval '1 month') m)
       or g.is_say > 1 then
      continue;
    end if;
    begin
      insert into public.media_placements (unit_id, customer_id, work_id, commitment,
                                           start_date, end_date, source_quote_id, note)
      values (g.unit_id, g.customer_id, g.work_id,
              case g.status when 'dolu' then 'confirmed' else 'reserved' end,
              g.ps, g.pe, g.quote_id, 'Eski aylık kayıtlardan birleştirildi')
      returning id into v_id;
      update public.bookings set superseded_by_placement_id = v_id where id = any(g.ids);
      n := n + 1;
    exception when others then
      raise notice 'PS8: eski kayıt birleştirilemedi (unit %, %): %', g.unit_id, g.ps, sqlerrm;
    end;
  end loop;
  perform set_config('medyapark.eski_devral', '', true);
  perform set_config('medyapark.medya_sessiz', '', true);
  return n;
end;
$$;
revoke all on function public._ps8_eski_kesin_birlestir() from public, anon, authenticated;
