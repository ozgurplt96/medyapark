-- =====================================================================
-- Product Simplification S8 — Media Operations V2
--
-- Exact, exclusive STATIC placements and concurrent LED campaigns become
-- the operational write model. The monthly `bookings(unit_id, ym)` grid
-- stays as LEGACY evidence and as a month PROJECTION; it is no longer the
-- primary truth that screens write.
--
-- Sellable target (evidence-led, see CURRENT_PRODUCT_DECISIONS_SUPPLEMENT):
--   static exclusive  -> one physical sellable face      = units.id
--   concurrent LED    -> one commercial publication area = alt_mecralar.id
-- `alt_mecralar` already is the stable non-physical level the inventory
-- uses ("M1 Adana LED"), so NO new target table is introduced. Behaviour
-- is STRUCTURAL (`alt_mecralar.occupancy_mode`), never inferred from a name.
-- No fake LED hardware is created: the old single `P3-A` LED row stays only
-- as the anchor of legacy monthly rows and cannot receive a placement.
--
-- Additive only. Legacy columns and rows are kept.
-- =====================================================================

create extension if not exists btree_gist with schema extensions;

-- =====================================================================
-- 1. Structural occupancy behaviour on the sellable-area level
-- =====================================================================
alter table public.alt_mecralar
  add column if not exists occupancy_mode text not null default 'exclusive',
  add column if not exists creative_seconds integer;

alter table public.alt_mecralar drop constraint if exists alt_mecralar_occupancy_mode_check;
alter table public.alt_mecralar add constraint alt_mecralar_occupancy_mode_check
  check (occupancy_mode in ('exclusive','concurrent'));

-- The creative duration is a property of a concurrent publication target,
-- stated once, never re-typed per campaign (PO: 15 s). No frequency, loop
-- share or plays/hour columns: none of them is an established rule.
alter table public.alt_mecralar drop constraint if exists alt_mecralar_creative_seconds_check;
alter table public.alt_mecralar add constraint alt_mecralar_creative_seconds_check
  check (creative_seconds is null
         or (occupancy_mode = 'concurrent' and creative_seconds between 1 and 600));

-- =====================================================================
-- 2. Canonical placement / campaign record
-- =====================================================================
create table if not exists public.media_placements (
  id                   bigint generated by default as identity primary key,
  -- exactly ONE commercial target (explicit FKs, no polymorphic id)
  unit_id              bigint references public.units(id)        on delete restrict,
  alt_mecra_id         bigint references public.alt_mecralar(id) on delete restrict,
  customer_id          bigint not null references public.customers(id) on delete restrict,
  work_id              bigint references public.jobs(id)            on delete set null,
  contract_item_id     bigint references public.contract_items(id)  on delete set null,
  source_quote_id      bigint references public.quotes(id)          on delete set null,
  -- commercial commitment; the temporal state (upcoming/current/ended) is
  -- DERIVED from the dates and is never stored.
  commitment           text not null default 'reserved',
  start_date           date not null,
  end_date             date,                       -- NULL = "Bitiş bilinmiyor"
  note                 text,
  -- provenance only (e.g. historical LED spreadsheet lane "1.ARC"). NOT a
  -- screen id, NOT a slot, NOT used for any validation.
  legacy_lane          text,
  cancelled_at         timestamptz,
  cancelled_by_team_id bigint references public.team(id) on delete set null,
  created_by_team_id   bigint references public.team(id) on delete set null,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz,
  constraint media_placements_one_target check (num_nonnulls(unit_id, alt_mecra_id) = 1),
  constraint media_placements_commitment_check
    check (commitment in ('reserved','confirmed','cancelled')),
  constraint media_placements_period_order check (end_date is null or end_date >= start_date),
  constraint media_placements_cancel_meta
    check ((commitment = 'cancelled') = (cancelled_at is not null)),
  constraint media_placements_lane_len check (legacy_lane is null or length(legacy_lane) <= 40),
  -- Static exclusivity is a DATABASE boundary: two blocking placements on
  -- the same face can never overlap, whatever path writes them. Reserved
  -- and confirmed block; cancelled does not. Open end = unbounded range.
  constraint media_placements_no_static_overlap exclude using gist (
    unit_id with =,
    daterange(start_date, end_date, '[]') with &&
  ) where (unit_id is not null and commitment <> 'cancelled')
);

create index if not exists media_placements_unit_idx     on public.media_placements (unit_id)      where unit_id is not null;
create index if not exists media_placements_area_idx     on public.media_placements (alt_mecra_id) where alt_mecra_id is not null;
create index if not exists media_placements_customer_idx on public.media_placements (customer_id);
create index if not exists media_placements_work_idx     on public.media_placements (work_id)      where work_id is not null;
create index if not exists media_placements_dates_idx    on public.media_placements (start_date, end_date);

