-- =====================================================================
-- 3. Unified schedule view — the ONE normalized Media query surface
-- =====================================================================
-- Used by Today, Year, Work/Organization context, the notification check,
-- the basic export and (later) Reports V2. security_invoker: RLS of the
-- caller applies, so anon sees nothing.
--
-- precision:
--   exact     real start and end are known
--   open_end  real start known, end explicitly unknown
--   month     only the monthly bucket is trustworthy (legacy) — no day is
--             ever derived from `ym`
-- block_start / block_end: the range a record OCCUPIES for exclusivity.
--   placement -> its own dates (open end = unbounded)
--   legacy    -> its monthly bucket, narrowed to the real period when the
--                real period is known and lies inside that bucket.
create or replace view public.media_schedule
with (security_invoker = true) as
select 'placement'::text                                 as record_kind,
       p.id                                              as placement_id,
       null::bigint                                      as booking_id,
       p.unit_id,
       coalesce(p.alt_mecra_id, u.alt_mecra_id)          as alt_mecra_id,
       coalesce(u.mecra_id, a.mecra_id)                  as mecra_id,
       case when p.alt_mecra_id is not null then 'concurrent' else 'exclusive' end as occupancy_mode,
       p.customer_id, p.work_id, p.contract_item_id, p.source_quote_id,
       p.commitment,
       p.start_date, p.end_date,
       case when p.end_date is null then 'open_end' else 'exact' end as date_precision,
       null::text                                        as ym,
       p.start_date                                      as block_start,
       p.end_date                                        as block_end,
       null::text                                        as period_note,
       p.note, p.legacy_lane,
       p.created_by_team_id, p.created_at, p.updated_at, p.cancelled_at,
       u.name as unit_name, a.name as area_name, m.name as mecra_name,
       c.firma as customer_name, j.title as work_title, a.creative_seconds
  from public.media_placements p
  left join public.units u        on u.id = p.unit_id
  left join public.alt_mecralar a on a.id = coalesce(p.alt_mecra_id, u.alt_mecra_id)
  left join public.mecralar m     on m.id = coalesce(u.mecra_id, a.mecra_id)
  left join public.customers c    on c.id = p.customer_id
  left join public.jobs j         on j.id = p.work_id
union all
select 'legacy', null, b.id,
       b.unit_id, u.alt_mecra_id, u.mecra_id,
       coalesce(a.occupancy_mode, 'exclusive'),
       b.customer_id, b.work_id, null, b.source_quote_id,
       case b.status when 'dolu' then 'confirmed' else 'reserved' end,
       b.period_start, b.period_end,
       case when b.period_start is not null and b.period_end is not null then 'exact'
            when b.period_start is not null then 'open_end'
            else 'month' end,
       b.ym::text,
       case when b.period_start is not null and b.period_end is not null
                 and b.period_start <= k.bitis and b.period_end >= k.bas
            then greatest(b.period_start, k.bas) else k.bas end,
       case when b.period_start is not null and b.period_end is not null
                 and b.period_start <= k.bitis and b.period_end >= k.bas
            then least(b.period_end, k.bitis) else k.bitis end,
       b.period_note, b.note, null,
       null, null, null, null,
       u.name, a.name, m.name, c.firma, j.title, a.creative_seconds
  from public.bookings b
  join public.units u on u.id = b.unit_id
  left join public.alt_mecralar a on a.id = u.alt_mecra_id
  left join public.mecralar m     on m.id = u.mecra_id
  left join public.customers c    on c.id = b.customer_id
  left join public.jobs j         on j.id = b.work_id
  cross join lateral (select to_date(b.ym || '-01', 'YYYY-MM-DD') as bas,
                             (to_date(b.ym || '-01', 'YYYY-MM-DD') + interval '1 month - 1 day')::date as bitis) k
 where b.superseded_by_placement_id is null;

revoke all on public.media_schedule from anon;
grant select on public.media_schedule to authenticated;

-- Conflicts for one static face over [p_start, p_end] (NULL end = open).
-- Returns both canonical placements and still-effective legacy rows.
create or replace function public.media_conflicts(p_unit bigint, p_start date, p_end date,
                                                  p_exclude bigint default null)
returns table (record_kind text, placement_id bigint, booking_id bigint, customer_id bigint,
               block_start date, block_end date, date_precision text, ym text)
language sql stable security invoker
set search_path = public, pg_temp as $$
  select s.record_kind, s.placement_id, s.booking_id, s.customer_id,
         s.block_start, s.block_end, s.date_precision, s.ym
    from public.media_schedule s
   where s.unit_id = p_unit
     and s.occupancy_mode = 'exclusive'
     and s.commitment <> 'cancelled'
     and (p_exclude is null or s.placement_id is distinct from p_exclude)
     and daterange(s.block_start, s.block_end, '[]') && daterange(p_start, p_end, '[]')
   order by s.block_start;
$$;
revoke all on function public.media_conflicts(bigint, date, date, bigint) from public, anon;
grant execute on function public.media_conflicts(bigint, date, date, bigint) to authenticated;

-- Human-readable label of a target, used in movements and conflict lists.
create or replace function public._medya_hedef_adi(p_unit bigint, p_area bigint)
returns text language sql stable security definer
set search_path = public, pg_temp as $$
  select case when p_unit is not null then
           coalesce((select coalesce(a.name, m.name) || ' · ' || u.name
                       from public.units u
                       left join public.alt_mecralar a on a.id = u.alt_mecra_id
                       left join public.mecralar m on m.id = u.mecra_id
                      where u.id = p_unit), '#' || p_unit)
         else coalesce((select a.name from public.alt_mecralar a where a.id = p_area), '#' || p_area)
         end;
$$;
-- Returns only public inventory names; the invoker write paths need it.
revoke all on function public._medya_hedef_adi(bigint, bigint) from public, anon;
grant execute on function public._medya_hedef_adi(bigint, bigint) to authenticated;

create or replace function public._medya_donem(p_start date, p_end date)
returns text language sql immutable as $$
  select to_char(p_start, 'DD.MM.YYYY') || ' – '
         || coalesce(to_char(p_end, 'DD.MM.YYYY'), 'bitiş bilinmiyor');
$$;

-- =====================================================================
-- 4. Integrity trigger (target, Work/Organization, contract item, overlap)
-- =====================================================================
create or replace function public._trg_media_placements_dogrula() returns trigger
language plpgsql security definer
set search_path = public, auth, pg_temp as $$
declare
  v_mode text; v_active boolean; v_unit_area bigint;
  v_orgs int; c record; k record; v_lbl text; v_devral boolean;
begin
  v_devral := coalesce(current_setting('medyapark.eski_devral', true), '') = '1';

  if tg_op = 'INSERT' then
    -- actor comes from the JWT, never from the client payload
    if not public.is_admin() or new.created_by_team_id is null then
      new.created_by_team_id := public.current_team_id();
    end if;
    new.created_at := now();
    new.updated_at := null;
    if new.commitment = 'cancelled' then
      if not public.is_admin() then
        raise exception 'Yeni kayıt iptal durumunda oluşturulamaz.' using errcode = '23514';
      end if;
      new.cancelled_at := coalesce(new.cancelled_at, now());
    else
      new.cancelled_at := null; new.cancelled_by_team_id := null;
    end if;
  else
    if not public.is_admin() and new.created_by_team_id is distinct from old.created_by_team_id then
      raise exception 'Kaydın yazarı değiştirilemez.' using errcode = '42501';
    end if;
    new.created_at := old.created_at;
    if (old.unit_id is null) <> (new.unit_id is null) then
      raise exception 'Hedef türü (statik yüzey / eşzamanlı yayın alanı) değiştirilemez.'
        using errcode = '23514';
    end if;
    if old.commitment = 'cancelled' and new.commitment <> 'cancelled' then
      raise exception 'İptal edilmiş kayıt yeniden etkinleştirilemez; yeni kayıt oluşturun.'
        using errcode = '23514';
    end if;
    if new.commitment = 'cancelled' and old.commitment <> 'cancelled' then
      new.cancelled_at := now(); new.cancelled_by_team_id := public.current_team_id();
    elsif new.commitment = 'cancelled' then
      new.cancelled_at := old.cancelled_at; new.cancelled_by_team_id := old.cancelled_by_team_id;
    end if;
    new.updated_at := now();
  end if;

  -- ---- target ---------------------------------------------------------
  if new.unit_id is not null then
    select coalesce(a.occupancy_mode, 'exclusive'), u.active, u.alt_mecra_id
      into v_mode, v_active, v_unit_area
      from public.units u left join public.alt_mecralar a on a.id = u.alt_mecra_id
     where u.id = new.unit_id;
    if v_mode = 'concurrent' then
      raise exception 'Bu pozisyon eşzamanlı bir yayın alanına ait; kampanya alanın kendisine eklenir.'
        using errcode = '23514';
    end if;
    if not v_active and (tg_op = 'INSERT' or new.unit_id is distinct from old.unit_id) then
      raise exception '%: pozisyon pasif, satışa kapalı.', public._medya_hedef_adi(new.unit_id, null)
        using errcode = '23514';
    end if;
  else
    select occupancy_mode into v_mode from public.alt_mecralar where id = new.alt_mecra_id;
    if v_mode is distinct from 'concurrent' then
      raise exception 'Bu alan eşzamanlı yayın alanı değil; yerleşim tek bir yüzeye yapılır.'
        using errcode = '23514';
    end if;
  end if;

  -- ---- Work <-> Organization: never contradictory ------------------------
  if new.work_id is not null and (tg_op = 'INSERT'
       or new.work_id is distinct from old.work_id or new.customer_id is distinct from old.customer_id) then
    select count(*) into v_orgs from (
      select customer_id from public.jobs where id = new.work_id and customer_id is not null
      union select customer_id from public.work_parties where job_id = new.work_id and customer_id is not null) o;
    if v_orgs > 0 and not exists (
         select 1 from public.jobs where id = new.work_id and customer_id = new.customer_id
         union all
         select 1 from public.work_parties where job_id = new.work_id and customer_id = new.customer_id) then
      raise exception 'Seçilen kurum bu işin taraflarından biri değil.' using errcode = '23514';
    end if;
  end if;

  -- ---- optional contract item: context only, must belong here ----------
  if new.contract_item_id is not null and (tg_op = 'INSERT'
       or new.contract_item_id is distinct from old.contract_item_id
       or new.customer_id is distinct from old.customer_id or new.work_id is distinct from old.work_id) then
    select ct.customer_id, ct.job_id into c
      from public.contract_items ci join public.contracts ct on ct.id = ci.contract_id
     where ci.id = new.contract_item_id;
    if not (c.customer_id = new.customer_id or (new.work_id is not null and c.job_id = new.work_id)) then
      raise exception 'Sözleşme kalemi bu kurum ya da iş ile ilişkili değil.' using errcode = '23514';
    end if;
  end if;

  -- ---- static exclusivity, including still-effective legacy rows --------
  if new.unit_id is not null and new.commitment <> 'cancelled' and (tg_op = 'INSERT'
       or new.unit_id is distinct from old.unit_id or new.start_date is distinct from old.start_date
       or new.end_date is distinct from old.end_date or old.commitment = 'cancelled') then
    select * into k
      from public.media_conflicts(new.unit_id, new.start_date, new.end_date, new.id) x
     where not (v_devral and x.record_kind = 'legacy' and x.customer_id = new.customer_id)
     limit 1;
    if found then
      v_lbl := case when k.record_kind = 'legacy' and k.date_precision = 'month'
                    then 'eski ay kaydı (' || k.ym || ')'
                    else _medya_donem(k.block_start, k.block_end) end;
      raise exception '%: % ile çakışıyor.', public._medya_hedef_adi(new.unit_id, null), v_lbl
        using errcode = '23P01';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_media_placements_dogrula on public.media_placements;
create trigger trg_media_placements_dogrula
  before insert or update on public.media_placements
  for each row execute function public._trg_media_placements_dogrula();

-- Replacing a same-Organization legacy month record is explicit: only when
-- the trusted write path set the flag, and only rows of the SAME customer
-- on the SAME face that the placement covers.
create or replace function public._trg_media_placements_devral() returns trigger
language plpgsql security definer
set search_path = public, pg_temp as $$
begin
  if coalesce(current_setting('medyapark.eski_devral', true), '') = '1'
     and new.unit_id is not null and new.commitment <> 'cancelled' then
    update public.bookings b set superseded_by_placement_id = new.id
      from public.media_schedule s
     where s.booking_id = b.id and s.record_kind = 'legacy'
       and b.unit_id = new.unit_id and b.customer_id = new.customer_id
       and b.superseded_by_placement_id is null
       and daterange(s.block_start, s.block_end, '[]') && daterange(new.start_date, new.end_date, '[]');
  end if;
  return null;
end;
$$;
drop trigger if exists trg_media_placements_devral on public.media_placements;
create trigger trg_media_placements_devral
  after insert or update on public.media_placements
  for each row execute function public._trg_media_placements_devral();

-- Changing a published area's behaviour under live placements would make
-- existing rows contradictory. Admin-only already (RLS); this guards data.
create or replace function public._trg_alt_mecralar_mod_koru() returns trigger
language plpgsql security definer
set search_path = public, pg_temp as $$
begin
  if new.occupancy_mode is distinct from old.occupancy_mode then
    if new.occupancy_mode = 'concurrent' and exists (
         select 1 from public.media_placements p join public.units u on u.id = p.unit_id
          where u.alt_mecra_id = new.id and p.commitment <> 'cancelled') then
      raise exception 'Bu alanın yüzeylerinde etkin yerleşim var; yayın davranışı değiştirilemez.'
        using errcode = '23514';
    end if;
    if new.occupancy_mode = 'exclusive' and exists (
         select 1 from public.media_placements p
          where p.alt_mecra_id = new.id and p.commitment <> 'cancelled') then
      raise exception 'Bu alanda etkin kampanya var; yayın davranışı değiştirilemez.'
        using errcode = '23514';
    end if;
  end if;
  return new;
end;
$$;
drop trigger if exists trg_alt_mecralar_mod_koru on public.alt_mecralar;
create trigger trg_alt_mecralar_mod_koru
  before update of occupancy_mode on public.alt_mecralar
  for each row execute function public._trg_alt_mecralar_mod_koru();

-- History is not silently destroyed by an inventory delete. The FK would
-- refuse anyway; this gives the admin an actionable message instead.
create or replace function public._trg_medya_gecmis_koru() returns trigger
language plpgsql security definer
set search_path = public, pg_temp as $$
begin
  if (tg_table_name = 'units' and exists (select 1 from public.media_placements where unit_id = old.id))
     or (tg_table_name = 'alt_mecralar' and exists (select 1 from public.media_placements where alt_mecra_id = old.id))
     or (tg_table_name = 'customers' and exists (select 1 from public.media_placements where customer_id = old.id)) then
    raise exception 'Bu kaydın mecra yerleşim geçmişi var; silmek yerine pasife alın.'
      using errcode = '23503';
  end if;
  return old;
end;
$$;
