-- =====================================================================
-- 8. Public availability — privacy-safe monthly projection
-- =====================================================================
-- Same three columns as before (unit_id, ym, status) so the public site is
-- untouched. Owner-rights view (as before): anon never reads the base
-- tables, only this projection — no Organization, Work, contract, note or
-- exact period.
--   static placement -> every month it touches (a partial month counts as
--                       unavailable: conservative). Open end -> projected
--                       24 months past the current month.
--   legacy month row -> still counts, unless superseded.
--   concurrent LED   -> EXCLUDED. Campaign presence is not "full" and no
--                       capacity rule exists, so the public cart treats the
--                       LED area as requestable; sale is confirmed manually.
create or replace view public.booking_availability_public as
with eski as (
  select b.unit_id, b.ym::text as ym, b.status
    from public.bookings b
    join public.units u on u.id = b.unit_id
    left join public.alt_mecralar a on a.id = u.alt_mecra_id
   where u.active and b.superseded_by_placement_id is null
     and coalesce(a.occupancy_mode, 'exclusive') = 'exclusive'
), yeni as (
  select p.unit_id, to_char(m, 'YYYY-MM') as ym,
         case p.commitment when 'confirmed' then 'dolu' else 'rezerve' end as status
    from public.media_placements p
    join public.units u on u.id = p.unit_id
    cross join lateral generate_series(
      date_trunc('month', p.start_date::timestamp),
      date_trunc('month', coalesce(p.end_date::timestamp,
                                   date_trunc('month', localtimestamp) + interval '24 months')),
      interval '1 month') m
   where p.unit_id is not null and p.commitment <> 'cancelled' and u.active
), tum as (select * from eski union all select * from yeni)
select unit_id, ym::character(7) as ym,
       case when bool_or(status = 'dolu') then 'dolu' else 'rezerve' end as status
  from tum
 group by unit_id, ym;

-- =====================================================================
-- 9. approve_quote(): writes canonical placements, not monthly bookings
-- =====================================================================
-- A public quote item sells ONE calendar month (`ym`), so the commercial
-- unit itself is the month: the placement is that month's first..last day.
-- Consecutive months of the same face in the same Offer become ONE
-- placement. A face in a concurrent area becomes ONE campaign on the area.
-- Conflicts are reported and skipped exactly as before; a same-customer
-- legacy month row is replaced (superseded), not duplicated.
create or replace function public.approve_quote(p_quote_id bigint)
returns jsonb language plpgsql
set search_path = public, pg_temp as $$
declare
  q            record;
  r            record;
  cust_id      bigint;
  v_work_id    bigint;
  m_id         bigint;
  reserved     int     := 0;
  skipped      int     := 0;
  conflicts    text[]  := '{}';
  created_work boolean := false;
  job_title    text;
  cur_phase    text;
  phase_rank   jsonb   := '{"temas_takip":0,"teklif":1,"baski":2,"montaj":3,"yayinda_aktif":4}';
begin
  select * into q from quotes where id = p_quote_id;
  if not found then
    return jsonb_build_object('done', false, 'error', 'quote_not_found');
  end if;

  if q.status = 'onaylandi' then
    return jsonb_build_object(
      'done', true, 'already_approved', true,
      'reserved', 0, 'skipped', 0, 'conflicts', '[]'::jsonb,
      'customer_id', q.customer_id, 'work_id', q.work_id);
  end if;

  cust_id := q.customer_id;
  if cust_id is null and coalesce(q.eposta,'') <> '' then
    select id into cust_id from customers where eposta = q.eposta limit 1;
  end if;
  if cust_id is null and coalesce(q.firma,'') <> '' then
    select id into cust_id from customers where firma = q.firma limit 1;
  end if;
  if cust_id is null then
    insert into customers (firma, telefon, eposta, source_type, source_ref)
    values (coalesce(nullif(q.firma,''), nullif(q.customer_name,''), 'Müşteri'),
            q.telefon, q.eposta, 'quote', 'quotes#' || p_quote_id)
    returning id into cust_id;
    if coalesce(nullif(trim(q.customer_name),''),'') <> '' then
      insert into contacts (customer_id, name, phone, email, is_primary, source_type, source_ref)
      values (cust_id, trim(q.customer_name), q.telefon, q.eposta, true,
              'quote', 'quotes#' || p_quote_id);
    end if;
  end if;
  if q.customer_id is null then
    update quotes set customer_id = cust_id where id = p_quote_id;
  end if;

  v_work_id := q.work_id;
  select mecra_id into m_id
    from units
   where id = (select unit_id from quote_items
                where quote_id = p_quote_id and unit_id is not null limit 1);
  if v_work_id is null then
    job_title := coalesce(nullif(q.firma,''), nullif(q.customer_name,''), 'Müşteri')
                 || ' — Teklif #' || p_quote_id;
    insert into jobs (title, customer_id, mecra_id, status, lifecycle_status, note)
    values (job_title, cust_id, m_id, 'teklif', 'acik',
            'Onaylanan tekliften otomatik oluşturuldu.')
    returning id into v_work_id;
    created_work := true;
    update quotes set work_id = v_work_id where id = p_quote_id;
    insert into work_parties (job_id, customer_id, role)
    values (v_work_id, cust_id, 'account')
    on conflict do nothing;
  end if;

  -- Consecutive-month runs per target (gaps-and-islands on month index).
  perform set_config('medyapark.eski_devral', '1', true);
  for r in
    with it as (
      select distinct qi.unit_id, qi.ym,
             case when coalesce(a.occupancy_mode,'exclusive') = 'concurrent' then u.alt_mecra_id end as area_id,
             public._medya_hedef_adi(qi.unit_id, null) as unit_name,
             to_date(qi.ym || '-01', 'YYYY-MM-DD') as ay
        from quote_items qi
        join units u on u.id = qi.unit_id
        left join alt_mecralar a on a.id = u.alt_mecra_id
       where qi.quote_id = p_quote_id and qi.unit_id is not null and qi.ym is not null
    ), hedef as (
      select distinct case when area_id is null then unit_id end as unit_id, area_id,
             case when area_id is null then unit_name
                  else (select name from alt_mecralar where id = area_id) end as ad, ay
        from it
    ), ada as (
      select *, (extract(year from ay) * 12 + extract(month from ay))::int
                - row_number() over (partition by unit_id, area_id order by ay)::int as grp
        from hedef
    )
    select unit_id, area_id, min(ad) as ad, min(ay) as bas,
           (max(ay) + interval '1 month - 1 day')::date as bit
      from ada group by unit_id, area_id, grp
      order by 1, 2, 4
  loop
    begin
      if r.unit_id is not null and exists (
           select 1 from media_conflicts(r.unit_id, r.bas, r.bit) x
            where not (x.record_kind = 'legacy' and x.customer_id = cust_id)) then
        conflicts := array_append(conflicts, r.ad || ' · ' || to_char(r.bas, 'MM.YYYY')
                     || case when r.bit > (r.bas + interval '1 month')::date
                             then '–' || to_char(r.bit, 'MM.YYYY') else '' end);
        skipped := skipped + 1;
        continue;
      end if;
      insert into media_placements (unit_id, alt_mecra_id, customer_id, work_id, commitment,
                                    start_date, end_date, source_quote_id)
      values (r.unit_id, r.area_id, cust_id, v_work_id, 'confirmed', r.bas, r.bit, p_quote_id);
      reserved := reserved + 1;
    exception when exclusion_violation or check_violation then
      conflicts := array_append(conflicts, r.ad || ' · ' || to_char(r.bas, 'MM.YYYY'));
      skipped := skipped + 1;
    end;
  end loop;
  perform set_config('medyapark.eski_devral', '', true);

  select status into cur_phase from jobs where id = v_work_id;
  if coalesce((phase_rank ->> cur_phase)::int, 0) < 1 then
    update jobs set status = 'teklif' where id = v_work_id;
  end if;

  update quotes set status = 'onaylandi' where id = p_quote_id;

  insert into entries (job_id, customer_id, body, source, source_ref)
  values (v_work_id, cust_id,
          'Teklif #' || p_quote_id || ' onaylandı'
          || case when reserved > 0 then ' · ' || reserved || ' mecra kaydı oluşturuldu' else '' end
          || case when skipped  > 0 then ' · ' || skipped  || ' kayıt çakışma nedeniyle atlandı' else '' end,
          'system', 'quotes#' || p_quote_id);

  return jsonb_build_object(
    'done',         true,
    'reserved',     reserved,
    'skipped',      skipped,
    'conflicts',    to_jsonb(conflicts),
    'customer_id',  cust_id,
    'work_id',      v_work_id,
    'created_work', created_work);
end
$$;

